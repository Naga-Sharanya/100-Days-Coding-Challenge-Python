# 👉 Task: Create a REST API to manage tasks.

# Features:
# CRUD for tasks (create, update, delete, list)
# Task attributes: title, description, status, due_date
# Use Django REST Framework (DRF) or FastAPI



# 🔥 API Endpoints:
# - POST /tasks/ → Create a task
# - GET /tasks/ → List all tasks
# - GET /tasks/{id}/ → Retrieve task by ID
# - PUT /tasks/{id}/ → Update task
# - DELETE /tasks/{id}/ → Delete task

# 🎉 Expected Input (POST):
# {
#   "title": "Complete Project",
